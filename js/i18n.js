(function () {
  "use strict";
  var LANGS = ["en", "zh", "tw", "ja"];
  var lang = "en";
  function detect() {
    var h = (location.hash || "").match(/lang=(zh|tw|ja|en)/);
    if (h) return h[1];
    try { var s = localStorage.getItem("talisman-lang"); if (LANGS.indexOf(s) !== -1) return s; } catch (e) {}
    var n = (navigator.language || "en").toLowerCase();
    if (n.indexOf("zh-tw") === 0 || n.indexOf("zh-hk") === 0 || n.indexOf("zh-mo") === 0) return "tw";
    if (n.indexOf("zh") === 0) return "zh";
    if (n.indexOf("ja") === 0) return "ja";
    return "en";
  }
  lang = detect();
  var api = {
    get lang() { return lang; },
    langs: LANGS,
    t: function (key, vars) {
      var s = (window.I18N_STRINGS[lang] && window.I18N_STRINGS[lang][key]) || window.I18N_STRINGS.en[key] || key;
      if (vars) Object.keys(vars).forEach(function (k) { s = s.replace("{" + k + "}", vars[k]); });
      return s;
    },
    skillName: function (skill) {
      if (!skill) return "";
      if (lang === "zh") return skill.nameZh || skill.name;
      if (lang === "tw") return skill.nameTw || skill.name;
      if (lang === "ja") return skill.nameJa || skill.name;
      return skill.name;
    },
    skillNameByEn: function (enName, skillIndexByName) {
      var sk = skillIndexByName && skillIndexByName[enName];
      if (sk) return api.skillName(sk);
      var ex = window.I18N_EXTRA_SKILLS[enName];
      if (ex && lang !== "en") return ex[lang] || enName;
      return enName;
    },
    charmName: function (rarity) {
      if (lang === "zh") return rarity.nameZh || rarity.name;
      if (lang === "tw") return rarity.nameTw || rarity.name;
      if (lang === "ja") return rarity.nameJa || rarity.name;
      return rarity.name;
    },
    weaponName: function (en) {
      var w = window.I18N_WEAPONS[en];
      return w ? (w[lang] || en) : en;
    },
    setLang: function (l, rerender) {
      if (LANGS.indexOf(l) === -1) return;
      lang = l;
      try { localStorage.setItem("talisman-lang", l); } catch (e) {}
      document.documentElement.lang = l === "zh" ? "zh-CN" : l === "tw" ? "zh-TW" : l;
      api.applyStatic();
      if (rerender) rerender();
    },
    applyStatic: function () {
      document.querySelectorAll("[data-i18n]").forEach(function (el) {
        el.innerHTML = api.t(el.getAttribute("data-i18n"));
      });
      document.querySelectorAll(".lang-btn").forEach(function (b) {
        b.classList.toggle("active", b.getAttribute("data-lang") === lang);
      });
    },
  };
  window.I18N = api;
})();
